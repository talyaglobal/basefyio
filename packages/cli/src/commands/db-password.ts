import chalk from 'chalk';
import type { Ora } from 'ora';
import { apiClient, handleApiError } from '../lib/api.js';
import { getProjectConfig, writeEnvFile } from '../lib/config.js';
import {
  afterRotationLines,
  buildRotationReport,
  connectMatchesRotation,
  rotationWarningLines,
  type CredentialTarget,
  type ProjectConnectInfo,
} from '../lib/db-password.js';
import { confirmOrExit, requireLogin, resolveTargetProject } from '../lib/target-project.js';
import { createSpinner, error, printBox, printJson, success, warning } from '../lib/ui.js';

export interface RotatePasswordOptions {
  project?: string;
  readonly?: boolean;
  yes?: boolean;
  writeEnv?: boolean;
  json?: boolean;
}

/** `basefyio db rotate-password` — new database password, generated by the platform. */
export async function dbRotatePassword(options: RotatePasswordOptions) {
  requireLogin();
  const target: CredentialTarget = options.readonly ? 'readonly' : 'owner';
  let spinner: Ora | null = null;
  try {
    const project = await resolveTargetProject(options.project);

    if (target === 'readonly' && !project.dbReadonlyUser) {
      error(`"${project.name}" has no read-only database user. Create one on the project's Connect page in the dashboard first.`);
      process.exit(1);
    }

    // --write-env rewrites ./.env, which must belong to this same project.
    if (options.writeEnv) {
      if (target !== 'owner') {
        error('--write-env only applies to the owner password; .env holds no read-only credentials.');
        process.exit(1);
      }
      const linked = await getProjectConfig();
      if (linked?.projectId && linked.projectId !== project.id) {
        error(`This directory is linked to another project (${linked.projectId}); refusing to write its .env.`);
        process.exit(1);
      }
    }

    if (!options.json) {
      printBox(rotationWarningLines(target, project.name).join('\n'), {
        title: 'Rotate database password',
        borderColor: 'yellow',
      });
    }
    const confirmed = await confirmOrExit({
      yes: options.yes,
      action: 'rotate the database password',
      message: `Rotate the ${target === 'owner' ? 'owner' : 'read-only'} database password of "${project.name}"?`,
      typeName: project.name,
    });
    if (!confirmed) return;

    spinner = options.json ? null : createSpinner('Rotating the password…');
    const { password } =
      target === 'owner'
        ? await apiClient.rotateDbPassword(project.id)
        : await apiClient.rotateReadonlyDbPassword(project.id);
    if (!password) {
      spinner?.fail('The API did not return a new password');
      process.exit(1);
    }

    // The connection strings come from the platform, so what is printed is
    // exactly what the API now holds — never a string assembled here.
    let connect: ProjectConnectInfo | null = null;
    if (target === 'owner') {
      try {
        connect = await apiClient.getProjectConnect(project.id);
      } catch {
        connect = null;
      }
    }
    spinner?.succeed('Password rotated — the old password no longer works');
    spinner = null;

    if (connect && !connectMatchesRotation(connect, password)) {
      // Should never happen; if it does, the printed URIs would be wrong.
      warning('The connection details the API returned do not carry the new password yet; using the password only.');
      connect = null;
    }

    const report = buildRotationReport({
      projectId: project.id,
      target,
      password,
      user: target === 'readonly' ? project.dbReadonlyUser : undefined,
      connect,
    });

    let wroteEnv = false;
    if (options.writeEnv && connect) {
      const fresh = await apiClient.getProject(project.id);
      await writeEnvFile({ ...fresh, dbPassword: password }, connect);
      wroteEnv = true;
    } else if (options.writeEnv) {
      warning('Could not read the new connection details, so .env was not changed. Run: basefyio link');
    }

    if (options.json) {
      printJson({ ...report, envUpdated: wroteEnv });
      return;
    }

    console.log();
    if (report.user) console.log(`  ${chalk.gray('User')}         ${report.user}`);
    console.log(`  ${chalk.gray('Password')}     ${report.password}`);
    if (report.connectionString) console.log(`  ${chalk.gray('Pooled URI')}   ${report.connectionString}`);
    if (report.directConnectionString && report.directConnectionString !== report.connectionString) {
      console.log(`  ${chalk.gray('Direct URI')}   ${report.directConnectionString}`);
    }
    console.log();
    for (const line of afterRotationLines(target, wroteEnv)) {
      if (line.startsWith('Updated .env')) success(line);
      else warning(line);
    }
  } catch (err) {
    spinner?.fail('Password rotation failed');
    await handleApiError(err);
  }
}
