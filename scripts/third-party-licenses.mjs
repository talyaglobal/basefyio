#!/usr/bin/env node
// Writes THIRD_PARTY_LICENSES.md: every runtime npm dependency of the shipped
// workspaces (name, version, SPDX licence, from the package-lock files) and the
// container images a release is tested with (deploy/components.env).
// Usage: node scripts/third-party-licenses.mjs [output-file]
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2] || join(root, 'THIRD_PARTY_LICENSES.md');
const workspaces = [];
for (const dir of ['apps', 'packages']) {
  const base = join(root, dir);
  if (!existsSync(base)) continue;
  for (const n of readdirSync(base)) {
    if (existsSync(join(base, n, 'package-lock.json'))) workspaces.push(`${dir}/${n}`);
  }
}

const licenseOf = (p) => {
  const l = p.license ?? p.licenses;
  if (!l) return 'UNKNOWN';
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(' OR ');
  return l.type ?? 'UNKNOWN';
};

const deps = new Map(); // "name@version" -> licence
for (const ws of workspaces) {
  const lock = JSON.parse(readFileSync(join(root, ws, 'package-lock.json'), 'utf8'));
  for (const [path, p] of Object.entries(lock.packages ?? {})) {
    if (!path.includes('node_modules/') || p.dev || p.link) continue;
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (p.version) deps.set(`${name}@${p.version}`, licenseOf(p));
  }
}

const counts = {};
for (const l of deps.values()) counts[l] = (counts[l] ?? 0) + 1;

const lines = [];
lines.push('# Third-party licenses', '');
lines.push('Generated by `scripts/third-party-licenses.mjs` from the lockfiles of this release.', '');
lines.push(`## npm runtime dependencies (${deps.size})`, '');
lines.push(`Workspaces: ${workspaces.map((w) => '`' + w + '`').join(', ')}.`, '');
lines.push('| License | Packages |', '|---|---|');
for (const [l, c] of Object.entries(counts).sort((a, b) => b[1] - a[1])) lines.push(`| ${l} | ${c} |`);
lines.push('', '| Package | License |', '|---|---|');
for (const k of [...deps.keys()].sort()) lines.push(`| ${k} | ${deps.get(k)} |`);

const comp = join(root, 'deploy/components.env');
if (existsSync(comp)) {
  const imgs = readFileSync(comp, 'utf8')
    .split('\n')
    .map((l) => l.match(/^([A-Z_0-9]+_IMAGE[A-Z_0-9]*)="?([^"]+)"?$/))
    .filter(Boolean);
  lines.push('', '## Container images', '');
  lines.push('Pulled as-is from their publishers; each image carries its own licence notices.', '');
  lines.push('| Variable | Image |', '|---|---|');
  for (const [, k, v] of imgs) lines.push(`| ${k} | \`${v}\` |`);
}
lines.push('', '## Go modules', '', 'This repository contains no Go modules; Go components appear only inside the container images above.', '');
writeFileSync(out, lines.join('\n'));
console.log(`${out}: ${deps.size} npm packages, ${workspaces.length} workspaces`);
