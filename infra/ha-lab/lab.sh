#!/usr/bin/env bash
# Driver for the Postgres HA lab (infra/ha-lab). Runs on a developer machine
# with a local Docker daemon; it refuses to run against a remote daemon or a
# daemon that hosts the production stack.
#
#   ./lab.sh up           start everything, seed pg-replica from pg-primary
#   ./lab.sh status       roles, replication, HAProxy routing, Keycloak
#   ./lab.sh promote      fence the current primary (clean stop), then
#                         pg_ctl promote the standby; `promote --crash` kills
#                         the primary instead of stopping it
#   ./lab.sh failback     rebuild the fenced node as a standby of the new
#                         primary, then switch back so pg-primary leads again
#   ./lab.sh down         remove the lab's containers, volumes and state
#   ./lab.sh check        compose config + haproxy -c, nothing started
#   ./lab.sh build-image  build docker/postgres as basefyio-postgres:lab
#   ./lab.sh psql [node|pg-rw|pg-ro|pgbouncer] [psql args]
#
# Manual promotion only; Patroni replaces promote/failback at Stage 5.
set -euo pipefail

DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
STATE="$DIR/state"
ENV_FILE="$STATE/lab.env"
PROJECT=basefyio-ha-lab
NODES=(pg-primary pg-replica)
PGDATA_IN=/var/lib/postgresql/data
HAPROXY_IMAGE=haproxy:3.0.31-alpine@sha256:7430e63d3052198b18a40665b59a5826bc428e8bceb0c561d82258149ef855ee

log() { printf '\033[1;34m[lab]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[lab] %s\033[0m\n' "$*" >&2; exit 1; }

dc() { docker compose -p "$PROJECT" -f "$DIR/docker-compose.yml" --env-file "$ENV_FILE" "$@"; }

# Remove one lab state file (never a directory, never outside ./state).
unmark() { rm -f -- "${STATE:?}/${1:?}"; }

guard() {
  command -v docker >/dev/null || die "docker CLI not found"
  docker info >/dev/null 2>&1 || die "no Docker daemon reachable"
  case "${DOCKER_HOST:-}" in
    '' | unix://*) ;;
    *) die "DOCKER_HOST=$DOCKER_HOST is not a local socket; the lab only runs locally" ;;
  esac
  local ep
  ep=$(docker context inspect --format '{{.Endpoints.docker.Host}}' 2>/dev/null || echo unix://)
  case "$ep" in
    unix://* | npipe://*) ;;
    *) die "docker context points at $ep; the lab only runs locally" ;;
  esac
  if docker ps -a --format '{{.Names}} {{.Label "com.docker.compose.project.config_files"}}' |
    grep -E '^kolaybase-' | grep -q 'docker-compose.prod.yml'; then
    die "this daemon runs the production stack (kolaybase-* from docker-compose.prod.yml); refusing"
  fi
}

rand() { od -An -N16 -tx1 /dev/urandom | tr -d ' \n'; }

ensure_state() {
  mkdir -p "$STATE/pgbouncer"
  if [ ! -s "$ENV_FILE" ]; then
    (
      umask 077
      {
        echo "# generated by lab.sh; lab-only credentials"
        echo "LAB_PG_PASSWORD=$(rand)"
        echo "LAB_REPL_PASSWORD=$(rand)"
        echo "LAB_CHECK_PASSWORD=$(rand)"
        echo "LAB_KC_ADMIN_PASSWORD=$(rand)"
        echo "LAB_PGBOUNCER_ADMIN_PASSWORD=$(rand)"
      } >"$ENV_FILE"
    )
  fi
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  # Same shape as PgBouncerService.buildIni() in platform-api (auth_type
  # plain, transaction mode, server_lifetime 3600 ...), with pg-rw as the host
  # every [databases] line points at: the Stage 1 re-point.
  cat >"$STATE/pgbouncer/pgbouncer.ini" <<INI
[databases]
labdb = host=pg-rw port=5432 dbname=labdb
kolaybase = host=pg-rw port=5432 dbname=kolaybase

[pgbouncer]
listen_addr = 0.0.0.0
listen_port = 6432
auth_type = plain
auth_file = /etc/pgbouncer/userlist.txt
pool_mode = transaction
max_client_conn = 1000
default_pool_size = 20
min_pool_size = 0
reserve_pool_size = 5
reserve_pool_timeout = 3
server_lifetime = 3600
server_idle_timeout = 600
log_connections = 1
log_disconnections = 1
log_pooler_errors = 1
admin_users = pgbouncer_admin
stats_users = pgbouncer_admin
ignore_startup_parameters = extra_float_digits,search_path
INI
  printf '"basefyio" "%s"\n"pgbouncer_admin" "%s"\n' "$LAB_PG_PASSWORD" "$LAB_PGBOUNCER_ADMIN_PASSWORD" \
    >"$STATE/pgbouncer/userlist.txt"
  chmod 644 "$STATE/pgbouncer/pgbouncer.ini" "$STATE/pgbouncer/userlist.txt"
}

port_of() {
  case "$1" in
    pg-ro) echo 5433 ;;
    pgbouncer) echo 6432 ;;
    *) echo 5432 ;;
  esac
}

# psql from the lab's client container. $1 = host (a node, pg-rw, pg-ro or
# pgbouncer), then psql arguments.
q() {
  local host=$1
  shift
  dc exec -T client psql -h "$host" -p "$(port_of "$host")" -XqAt -v ON_ERROR_STOP=1 "$@"
}

node_running() { [ "$(docker inspect -f '{{.State.Running}}' "${PROJECT}-$1-1" 2>/dev/null)" = true ]; }

# Prints primary | replica | down.
role_of() {
  node_running "$1" || {
    echo down
    return
  }
  local r
  r=$(q "$1" -d postgres -c 'select pg_is_in_recovery()' 2>/dev/null) || {
    echo down
    return
  }
  if [ "$r" = f ]; then echo primary; else echo replica; fi
}

other() { if [ "$1" = pg-primary ]; then echo pg-replica; else echo pg-primary; fi; }

current_primary() {
  local n found=""
  for n in "${NODES[@]}"; do
    if [ "$(role_of "$n")" = primary ]; then
      [ -n "$found" ] && die "BOTH nodes answer as primary (split brain): stop one before continuing"
      found=$n
    fi
  done
  echo "$found"
}

wait_until() { # timeout_s description command...
  local t=$1 what=$2
  shift 2
  local i
  for ((i = 0; i < t; i++)); do
    if "$@" >/dev/null 2>&1; then return 0; fi
    sleep 1
  done
  die "timed out after ${t}s waiting for: $what"
}

is_role() { [ "$(role_of "$1")" = "$2" ]; }
is_streaming() {
  [ "$(q "$1" -d postgres -c "select status from pg_stat_wal_receiver" 2>/dev/null)" = streaming ]
}
rw_points_at() {
  [ "$(q pg-rw -d postgres -c "select current_setting('cluster_name') || '|' || pg_is_in_recovery()" 2>/dev/null)" = "$1|f" ]
}
keycloak_ready() { curl -fsS "http://127.0.0.1:${LAB_KEYCLOAK_PORT:-18080}/health/ready" >/dev/null; }

caught_up() { # standby lsn
  [ "$(q "$1" -d postgres -c "select pg_wal_lsn_diff(pg_last_wal_replay_lsn(), '$2') >= 0")" = t ]
}

lab_pg_image() { dc config --images 2>/dev/null | grep -m1 -E 'basefyio-postgres' || true; }

# Empty a stopped node's data and archive volumes (lab volumes only: the
# names are prefixed with the fixed project name).
wipe_node() {
  local node=$1 vol_base=${1//-/_} img
  img=$(lab_pg_image)
  [ -n "$img" ] || die "cannot resolve the lab Postgres image"
  node_running "$node" && die "refusing to wipe $node while it runs"
  log "wiping $node (lab volumes ${PROJECT}_${vol_base}_data and _wal_archive)"
  docker run --rm --network none \
    -v "${PROJECT}_${vol_base}_data:/d" -v "${PROJECT}_${vol_base}_wal_archive:/a" \
    --entrypoint bash "$img" -c 'find /d /a -mindepth 1 -delete'
}

cmd_check() {
  ensure_state
  dc config -q && log "compose config: ok"
  docker run --rm -v "$DIR/haproxy/haproxy.cfg:/c/haproxy.cfg:ro" "$HAPROXY_IMAGE" \
    haproxy -c -f /c/haproxy.cfg && log "haproxy -c: ok"
}

cmd_build_image() {
  docker build -t basefyio-postgres:lab "$DIR/../../docker/postgres"
  log "built basefyio-postgres:lab; run: LAB_PG_IMAGE=basefyio-postgres:lab ./lab.sh up"
  log "(same Dockerfile as prod, but apt PostGIS is unpinned: not byte-identical to the prod digest)"
}

remember_image_override() {
  [ -n "${LAB_PG_IMAGE:-}" ] || return 0
  local tmp="$ENV_FILE.tmp"
  grep -v '^LAB_PG_IMAGE=' "$ENV_FILE" >"$tmp" || true
  echo "LAB_PG_IMAGE=$LAB_PG_IMAGE" >>"$tmp"
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
}

cmd_up() {
  local override=${LAB_PG_IMAGE:-}
  ensure_state
  LAB_PG_IMAGE=$override remember_image_override
  echo pg-primary >"$STATE/pg-replica.upstream"
  unmark pg-primary.upstream
  unmark pg-primary.fenced
  unmark pg-replica.fenced
  dc build
  dc up -d client pg-primary
  wait_until 120 "pg-primary accepts connections" is_role pg-primary primary
  log "pg-primary is up (primary)"
  dc up -d pg-replica
  wait_until 300 "pg-replica streaming from pg-primary" is_streaming pg-replica
  log "pg-replica is streaming"
  dc up -d rc-primary rc-replica haproxy pgbouncer
  wait_until 30 "pg-rw -> pg-primary" rw_points_at pg-primary
  dc up -d keycloak
  log "waiting for Keycloak (the first start builds its configuration, 1-3 min)"
  wait_until 300 "Keycloak /health/ready" keycloak_ready
  cmd_status
}

cmd_status() {
  ensure_state
  local n st role recv lag p kc="${PROJECT}-keycloak-1"
  printf '\n%-11s %-16s %-8s %-13s %s\n' NODE STATE ROLE WAL_RECEIVER REPLAY_LAG_BYTES
  for n in "${NODES[@]}"; do
    st=$(docker inspect -f '{{.State.Status}}' "${PROJECT}-$n-1" 2>/dev/null || echo absent)
    role=$(role_of "$n")
    recv=-
    lag=-
    if [ "$role" = replica ]; then
      recv=$(q "$n" -d postgres -c "select coalesce((select status from pg_stat_wal_receiver), 'none')" 2>/dev/null || echo '?')
      lag=$(q "$n" -d postgres -c "select coalesce(pg_wal_lsn_diff(pg_last_wal_receive_lsn(), pg_last_wal_replay_lsn()), 0)::bigint" 2>/dev/null || echo '?')
    fi
    if [ -e "$STATE/$n.fenced" ]; then st="$st,fenced"; fi
    printf '%-11s %-16s %-8s %-13s %s\n' "$n" "$st" "$role" "$recv" "$lag"
  done
  p=$(current_primary)
  echo
  if [ -n "$p" ]; then
    log "pg_stat_replication on $p (application | client | state | sync | replay lag bytes):"
    q "$p" -d postgres -F ' | ' -c \
      "select application_name, client_addr, state, sync_state, pg_wal_lsn_diff(pg_current_wal_lsn(), replay_lsn)::bigint from pg_stat_replication" \
      2>/dev/null || true
    log "replication slots on $p (name | active | wal_status):"
    q "$p" -d postgres -F ' | ' -c "select slot_name, active, wal_status from pg_replication_slots" 2>/dev/null || true
  else
    log "no node answers as primary"
  fi
  echo
  log "pg-rw     -> $(q pg-rw -d postgres -c "select current_setting('cluster_name') || ' (in_recovery=' || pg_is_in_recovery() || ')'" 2>/dev/null || echo unreachable)"
  log "pg-ro     -> $(q pg-ro -d postgres -c "select current_setting('cluster_name') || ' (in_recovery=' || pg_is_in_recovery() || ')'" 2>/dev/null || echo unreachable)"
  log "pgbouncer -> $(q pgbouncer -d labdb -c "select 'ok'" 2>/dev/null || echo unreachable)"
  log "keycloak  -> health $(if keycloak_ready 2>/dev/null; then echo ready; else echo NOT-ready; fi)," \
    "started $(docker inspect -f '{{.State.StartedAt}}' "$kc" 2>/dev/null || echo -)," \
    "restarts $(docker inspect -f '{{.RestartCount}}' "$kc" 2>/dev/null || echo -)"
  log "HAProxy stats: http://127.0.0.1:${LAB_HAPROXY_STATS_PORT:-17000}/"
}

cmd_promote() {
  ensure_state
  local mode=${1:-clean} old new t0
  old=$(current_primary)
  [ -n "$old" ] || die "no current primary"
  new=$(other "$old")
  is_role "$new" replica || die "$new is not a running standby"
  is_streaming "$new" || log "warning: $new is not streaming right now; it promotes with what it has"
  log "promoting $new; fencing $old first ($mode)"
  t0=$(date +%s)
  # Fence before promote (plan section 3.3, control 6): the old primary is
  # gone before a second node becomes writable, and the .fenced mark keeps
  # it from ever starting again with its old data.
  touch "$STATE/$old.fenced"
  if [ "$mode" = --crash ]; then
    docker kill "${PROJECT}-$old-1" >/dev/null
  else
    # A clean (fast) shutdown streams all WAL to the connected standby first.
    dc stop -t 30 "$old"
  fi
  dc exec -T -u postgres "$new" pg_ctl promote -w -t 60 -D "$PGDATA_IN"
  wait_until 60 "$new answers as primary" is_role "$new" primary
  wait_until 30 "pg-rw -> $new" rw_points_at "$new"
  unmark "$new.upstream"
  log "promoted $new in $(($(date +%s) - t0))s; pg-rw follows it. $old is stopped and fenced."
  log "Keycloak was not touched. ./lab.sh failback restores the original roles."
}

reseed_as_standby() { # node upstream
  local node=$1 up=$2 lsn
  wipe_node "$node"
  echo "$up" >"$STATE/$node.upstream"
  unmark "$node.fenced"
  dc start "$node"
  wait_until 300 "$node streaming from $up" is_streaming "$node"
  lsn=$(q "$up" -d postgres -c 'select pg_current_wal_lsn()')
  wait_until 120 "$node caught up to $lsn" caught_up "$node" "$lsn"
  log "$node is a streaming standby of $up and caught up"
}

cmd_failback() {
  ensure_state
  local cur fenced
  cur=$(current_primary)
  [ -n "$cur" ] || die "no current primary"
  fenced=$(other "$cur")
  if [ "$cur" = pg-primary ] && is_role pg-replica replica; then
    log "roles are already pg-primary=primary, pg-replica=replica; nothing to do"
    return
  fi
  if node_running "$fenced" && [ ! -e "$STATE/$fenced.fenced" ]; then
    die "$fenced is running and not fenced; inspect with ./lab.sh status first"
  fi
  if node_running "$fenced"; then dc stop "$fenced"; fi
  log "1/3 rebuild $fenced as a standby of $cur"
  reseed_as_standby "$fenced" "$cur"
  if [ "$cur" = pg-primary ]; then
    cmd_status
    return
  fi
  log "2/3 planned switchover back: fence $cur, promote $fenced"
  cmd_promote clean
  log "3/3 rebuild $cur as a standby of $fenced"
  reseed_as_standby "$cur" "$fenced"
  cmd_status
}

cmd_down() {
  ensure_state
  dc down -v --remove-orphans
  find "${STATE:?}" -mindepth 1 -delete
  rmdir "${STATE:?}"
  log "lab removed (containers, the lab's volumes, ./state)"
}

cmd_psql() {
  ensure_state
  local host=${1:-pg-rw}
  [ $# -gt 0 ] && shift
  dc exec client psql -h "$host" -p "$(port_of "$host")" -d "${LAB_DB:-labdb}" "$@"
}

main() {
  local cmd=${1:-help}
  [ $# -gt 0 ] && shift
  case "$cmd" in
    up | status | promote | failback | down | check | psql | build-image) guard ;;
  esac
  case "$cmd" in
    up) cmd_up ;;
    status) cmd_status ;;
    promote) cmd_promote "${1:-clean}" ;;
    failback) cmd_failback ;;
    down) cmd_down ;;
    check) cmd_check ;;
    build-image) cmd_build_image ;;
    psql) cmd_psql "$@" ;;
    *)
      sed -n '2,18p' "$0"
      exit 2
      ;;
  esac
}

# Sourcing (smoke.sh does) only loads the functions.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  main "$@"
fi
